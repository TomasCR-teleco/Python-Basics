###6. Escribe un programa que pida al usuario cuántos perros hay en un parque y calcule cuántas
###cabezas, patas y orejas hay en total.
perros = int(input("¿Cuantos perros hay en el parque?\n"))
cabezas = perros
patas = perros * 4
orejas = perros * 2
print(f"Hay {perros} perros, {cabezas} cabezas, {patas} patas y {orejas} orejas.")


